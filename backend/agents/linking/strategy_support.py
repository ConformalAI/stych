"""Which matching strategies are available for a given join plan, and why not.

A DB-backed join must never quietly fall back to the loaded 10K sample: a user
who joined two connected tables would get an answer computed from a fraction of
their data with no way to tell. Anything that cannot run at full scale is
refused here with a reason the UI can show.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from datasources.join_planner import JoinPlan

EXACT = "exact"
SEMANTIC = "semantic"

# Similarity strategies computed from string content alone. Each is a pure
# function of the two key values, so it can be evaluated over candidate pairs
# generated by the source without materializing either input.
LEXICAL_STRATEGIES = frozenset(
    {
        "levenshtein",
        "jaro_winkler",
        "token_sort",
        "token_set",
        "partial_ratio",
        "cosine_tfidf",
        "soundex",
        "metaphone",
    }
)

SOURCE_SIDE = "source_side"
MATERIALIZED = "materialized"
UNAVAILABLE = "unavailable"


@dataclass(frozen=True)
class StrategyDecision:
    mode: str
    reason: str
    user_message: Optional[str] = None

    @property
    def available(self) -> bool:
        return self.mode != UNAVAILABLE


def resolve_strategy(strategy: str, plan: JoinPlan) -> StrategyDecision:
    """Decide how *strategy* runs for *plan*."""
    name = (strategy or EXACT).strip().lower()

    if not plan.source_side:
        # Uploads are already complete; connected or mixed inputs are streamed
        # in full by execution.join_inputs. Neither path uses attached previews.
        if name in LEXICAL_STRATEGIES or name == EXACT:
            return StrategyDecision(MATERIALIZED, f"local_data:{plan.reason}")
        if name == SEMANTIC:
            return StrategyDecision(
                UNAVAILABLE,
                "semantic_deferred",
                "Semantic/vector joins are deferred from the current connector-parity scope.",
            )
        return StrategyDecision(UNAVAILABLE, "unknown_strategy", f"Unknown strategy '{strategy}'.")

    if name == EXACT:
        return StrategyDecision(SOURCE_SIDE, "exact_join_pushdown")

    if name == SEMANTIC:
        return StrategyDecision(
            UNAVAILABLE,
            "semantic_requires_egress",
            "Semantic matching embeds your column values with an external model and stores "
            "the vectors outside your database, so it is not available for connected "
            "sources in the current parity scope. Use an exact or lexical strategy.",
        )

    if name in LEXICAL_STRATEGIES:
        return StrategyDecision(
            MATERIALIZED,
            "full_source_stream",
            f"'{name}' matching streams the complete source inputs into the session; "
            "attached preview rows are used only to plan the join.",
        )

    return StrategyDecision(UNAVAILABLE, "unknown_strategy", f"Unknown strategy '{strategy}'.")
